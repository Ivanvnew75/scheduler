package job

import (
	"testing"
	"time"
)

// Slot задаёт «окно» рассылки и одновременно ключ блокировки.
// Тест защищает от незаметной смены гранулярности: если формат
// поменять на минуты, две реплики, стартовавшие в разные минуты,
// разошлют вопрос дважды.
func TestSlotIsHourly(t *testing.T) {
	base := time.Date(2026, 8, 10, 9, 0, 0, 0, time.UTC)

	if got, want := Slot(base), "2026-08-10T09"; got != want {
		t.Errorf("Slot = %q, ожидалось %q", got, want)
	}

	// Разные минуты одного часа — один и тот же слот.
	if Slot(base) != Slot(base.Add(59*time.Minute)) {
		t.Error("минуты внутри часа не должны менять слот")
	}
	// Разные часы — разные слоты, иначе вечерняя рассылка была бы
	// заблокирована утренней.
	if Slot(base) == Slot(base.Add(12*time.Hour)) {
		t.Error("утренняя и вечерняя рассылки обязаны иметь разные слоты")
	}
}
